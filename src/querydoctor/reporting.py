"""Persisting and rendering reports (JSON, Markdown)."""

from __future__ import annotations

import json
from pathlib import Path

from querydoctor.bench import BenchResult
from querydoctor.errors import QueryDoctorError
from querydoctor.formatting import fmt_bytes, fmt_ms, fmt_percent, fmt_speedup
from querydoctor.models import FullReport, QueryReport


def save_json(model: FullReport | BenchResult, path: Path) -> None:
    """Write a report to ``path`` as pretty JSON, creating parent folders."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(model.model_dump_json(indent=2), encoding="utf-8")


def load_report(path: Path) -> FullReport:
    """Load a report saved by :func:`save_json`."""
    if not path.exists():
        raise QueryDoctorError(f"No saved report at {path}. Run `querydoctor analyze` first.")
    return FullReport.model_validate(json.loads(path.read_text(encoding="utf-8")))


def _query_block(q: QueryReport) -> list[str]:
    lines = [f"### {q.title or q.id}", "", "```sql", q.sql, "```", ""]
    if q.status == "error":
        return [*lines, f"Could not analyze: {q.message}", ""]
    lines.append(q.message)
    lines.append("")
    for rec in q.recommendations:
        write = f", inserts +{fmt_percent(rec.write_overhead)}" if rec.write_overhead else ""
        lines += [
            f"**{rec.rank}. `{rec.create_sql}`**",
            "",
            f"{fmt_ms(rec.baseline_ms)} to {fmt_ms(rec.after_ms)} ({fmt_speedup(rec.speedup)}), "
            f"+{fmt_bytes(rec.size_bytes)}{write}, confidence {rec.confidence}.",
            "",
            rec.explanation,
            "",
        ]
    return lines


def render_markdown(report: FullReport) -> str:
    """Render an analysis report as Markdown."""
    lines = [
        "# QueryDoctor report",
        "",
        f"Database `{report.database}` ({fmt_bytes(report.database_bytes)}), "
        f"analyzed in {report.duration_s:.1f} s.",
        "",
        f"**{report.headline}**",
        "",
    ]
    for q in report.queries:
        lines += _query_block(q)
    lines += ["## Migration", "", "```sql", report.migration_sql.rstrip(), "```", ""]
    lines += ["## Rollback", "", "```sql", report.rollback_sql.rstrip(), "```", ""]
    return "\n".join(lines)


def render_bench_markdown(result: BenchResult) -> str:
    """Render ``docs/benchmarks.md`` from a benchmark run."""
    report, env = result.report, result.environment
    rows = sum(t.rows for t in report.tables)
    lines = [
        "# Benchmarks",
        "",
        "Generated by `querydoctor bench`. Every number below was measured, not estimated.",
        "",
        f"**Headline: {report.headline}.**",
        "",
        "## Environment",
        "",
        f"- Dataset: {rows:,} rows across {len(report.tables)} tables "
        f"({fmt_bytes(report.database_bytes)} SQLite file)",
        f"- SQLite {env.sqlite}, Python {env.python}, {env.platform}",
        f"- QueryDoctor {env.querydoctor}, total run time {report.duration_s:.0f} s",
        "",
        "## Method",
        "",
        "1. The database is copied with SQLite's backup API; the original is never modified.",
        "2. `ANALYZE` runs on the copy so the planner has realistic statistics.",
        "3. Each query is executed once to warm caches, then 3 to 7 times; the median is kept.",
        "4. Each candidate index is created, checked in the query plan, timed, and dropped.",
        "5. A candidate is only recommended if the result set is identical to the baseline.",
        "",
        "## Results",
        "",
        "| Query | Before | After | Speedup | Recommended indexes |",
        "|---|---:|---:|---:|---|",
    ]
    for q in report.queries:
        if q.status == "error":
            lines.append(f"| {q.title} | n/a | n/a | n/a | error: {q.message} |")
            continue
        none_text = {
            "already_fast": "none needed, already fast",
            "no_improvement": "none found that beats the 1.25x threshold",
        }.get(q.status, "none")
        indexes = "<br>".join(f"`{r.create_sql}`" for r in q.recommendations) or none_text
        lines.append(
            f"| {q.title} | {fmt_ms(q.baseline_ms or 0)} | {fmt_ms(q.final_ms or 0)} | "
            f"{fmt_speedup(q.speedup or 1)} | {indexes} |"
        )
    lines += [
        "",
        f"Total: {fmt_ms(report.total_baseline_ms)} before, {fmt_ms(report.total_final_ms)} after "
        f"across the whole suite.",
        "",
        "## Queries",
        "",
    ]
    for q in report.queries:
        lines += ["```sql", f"-- {q.id}: {q.title}", q.sql, "```", ""]
    lines += [
        "## Reproduce",
        "",
        "```bash",
        "querydoctor seed",
        "querydoctor bench",
        "```",
        "",
        "Absolute timings depend on your machine; the ratios are what to compare.",
        "",
    ]
    return "\n".join(lines)
